/**
 * L1 项目标签（`metadata.project`）+ 适用范围标签（`metadata.scope`）的**契约模块**。
 *
 * 职责：定义两个标签的取值空间与归一化规则，并回答「一条记忆最终该挂到哪个项目路径」。
 * 计划出处：`plan/memory-system/completed/L1-项目与范围标签-计划.md` 任务 0（先立契约，后写回填器）。
 *
 * 边界（刻意收紧，调用方不得越界）：
 *   - **纯函数 + 纯常量，零 import**：不读文件、不写文件、不发网络请求、不调模型。
 *     任何路径判定的重活都交给调用方，本模块只管**取值空间与形态归一**。
 *   - **不 import 任何需要 pi 上下文的模块**（无 pi 运行时依赖，可被脚本/子进程/测试直接 import）。
 *   - **不依赖 `node:path`**：`path.normalize` 在这里反而碍事（它按宿主平台把 `/` 翻回 `\`、
 *     并可能吞掉盘符尾斜杠），而标签必须在 Windows 盘符 + 正斜杠之间**稳定**表示，
 *     所以归一化全部自己用字符串做，保证在任何平台上跑出同一个结果。
 *
 * 两条标签的正交关系：
 *   `scope` 决定「这条记忆适用的范围有多宽」，`project` 决定「它挂在哪个项目路径下」。
 *   两者由 {@link projectForScope} 合成 —— 调用方不需要自己写分支，也就不会写出
 *   「scope 是 global 却带着 project」这种自相矛盾的组合。
 *
 * ## 取值空间：三档（2026-09-30，**用户最终裁定**）
 *
 * | 值 | 含义 | `project` 填什么 |
 *   |---|---|---|
 *   | `self` | 属于某个项目（出了那个目录就不成立） | 判定出的项目路径 |
 *   | `global` | **没有项目**（换个项目依然成立） | 空串（强制） |
 *   | `unknown` | **判不了** | 空串（不作过滤依据） |
 *
 * `global` **不是第三种项目，而是"没有项目"**（见 `project-attribution-model` 的定义）。
 * 那些硬塞进某个仓库就一定是错的记忆——如横跨 4 个目录的「协作规范」类——必须能表达成 `global`。
 *
 * ⚠ **`subtree` 档已作废，不要再加回来。** 它的本意是「挂到上层路径，让子项目之间互相可见」，
 * 但这与"召回判定 = 路径包含"那套设计冲突，且实测难判（30 条尺子里 12 条 = 40% 拿不准）。
 * 需要更宽的可见性时，走 `project` 本身指向更上层路径，不要新造 scope 档位。
 *
 * ## 「项目」的定义不在本文件
 *
 * **权威定义见仓库内 `agent/extensions/memory-system/项目归属定义.md`**（2026-10-01 落盘）：
 * 项目 = 一个有专有身份、能独立交付的**最小工作单元**；`C:\dev\code_java\wangxin` 是仓库/工作区、
 * **不是**项目。要改判定口径就改那份文档，并同步重跑评测尺子。
 * ⚠ **别拿"这是不是项目"来质疑 `project` 字段里的某个路径值** —— 该字段是判定结果，
 * 且容器目录（仓库）是合法的兜底取值；用那三条机械规则去反推已判好的字段会得出错误结论。
 *
 * `unknown` 是**显式的弃权档**，不是占位符：原先「判不了就不写字段」的 fail-open 行为会让
 * 「判不了」在数据里彻底不可见——将来召回过滤遇到没有 `scope` 的记录，代码只能自己猜怎么处理。
 * 显式取值可计数、可被消费者识别、可与「确定没有项目」区分：
 *   `global` = 确定没有项目（无条件注入）｜`unknown` = 不知道（不过滤，但可标出来）。
 * 这两者召回行为不同，混成一个就丢了信息。
 */

