//  取值空间
// ══════════════════════════════════════════════════════════════

/**
 * `metadata.scope` 的全部合法取值（闭集，三值，不多不少）。
 *
 * 用 `as const` 保住字面量类型，`ScopeValue` 由它推导，杜绝「类型里手抄一份、值里又写一份」
 * 这种两处不同步的经典错误。`self` / `global` 沿用 `project-attribution-model` 的定义，
 * `unknown` 是「判不了」的显式弃权档。
 */
export const SCOPE_VALUES = ["self", "global", "unknown"] as const;

/** `scope` 的合法取值类型。 */
export type ScopeValue = (typeof SCOPE_VALUES)[number];

/**
 * `v` 是否**严格**等于某个合法 scope 值（区分大小写，不做任何宽松处理）。
 *
 * 参数：任意值（`unknown`）。
 * 返回：true 表示 `v` 可直接当 `ScopeValue` 用。
 * 设计意图：这是「零容错」的那道闸门，供**类型收窄**（`v is ScopeValue`）与
 * 已归一数据的快路径使用。凡是来路不明的数据（模型输出、存量 JSON）都应先过
 * {@link normalizeScope}，不要直接用它。
 */
export function isScopeValue(v: unknown): v is ScopeValue {
	return typeof v === "string" && (SCOPE_VALUES as readonly string[]).includes(v);
}

/**
 * 把任意输入归一成一个合法 `ScopeValue`，**归不了一律返回 `null`**。
 *
 * 接受的宽松写法只有两种：**首尾空白**、**大小写差异**（`" SELF "` / `"Global"`）。
 * 这两类是传输与手抄造成的噪声，除掉它们不改变语义。
 *
 * 刻意**不做**的：同义词映射（`subtree` → `self`、`project` → `self`、`global-only` → `global` …）。
 * 理由见设计意图：存量 199 条 `metadata.scope` 是自由文本，取值里混着
 * `subtree`(已作废的旧档) / `project`(41) / `memory-system`(36) / `workflow`(32) / `module`(19) ——
 * 一半填的是项目名或模块名。一旦开了同义词这张表，这些垃圾会被"洗"成看似合法的标签，
 * 从此再也无法与真值区分；而 `null` 是诚实的：它把"这里有脏数据"这件事显式交给上层处理
 * （丢弃 / 标 unknown 重判 / 报警），代价只是丢一条标签，换来的是词表第一天就受控。
 *
 * 参数：任意值（模型输出、JSON 字段、命令行参数…）。
 * 返回：合法 scope 值，或 `null`。**绝不回退到 `"self"`** —— 静默兜底会让脏数据不可见，
 * 且把一条 `global` 记忆错挂到项目上（错误归属比没有归属更难查）。
 */
export function normalizeScope(v: unknown): ScopeValue | null {
	if (typeof v !== "string") return null;
	const s = v.trim().toLowerCase();
	return isScopeValue(s) ? s : null;
}

// ══════════════════════════════════════════════════════════════
//  项目路径标签
// ══════════════════════════════════════════════════════════════

/** 单趟归一化的最大迭代次数（只为吃掉嵌套引号，见 {@link normalizeProjectTag}）。 */
const MAX_NORMALIZE_PASSES = 3;

/**
 * 单趟归一化：去首尾空白 → 去**一对**成对引号（再 trim 一次）→ 反斜杠全转正斜杠并压缩重复斜杠
 * → 去尾部多余 `/`（盘符根 `C:/` 除外）。**不做绝对路径校验**。
 *
 * 私有函数，单独拆出来是为了让 {@link normalizeProjectTag} 能反复套用到不动点。
 * 形状校验必须留到不动点之后：嵌套引号（`""C:/x""`）要剥两轮才露相，
 * 若每趟就判"非绝对路径 → 作废"，第一趟就会把 `""C:/x""` 误杀成空串。
 */
function normalizeOnce(raw: string): string {
	let s = raw.trim();
	// 成对引号：模型经常把路径当字符串值再包一层引号（"C:/dev/x"），引号不是路径的一部分。
	// 必须成对且长度 ≥ 2 才剥，避免把 `C:/a/"b` 这类真带引号的合法目录名误伤。
	if (s.length >= 2 && ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'")))) {
		s = s.slice(1, -1).trim();
	}
	if (!s) return "";
	s = s.replace(/\\/g, "/").replace(/\/{2,}/g, "/"); // 反斜杠全转正斜杠；`//` 压成 `/`（UNC 前缀不适用于本机形态）
	// 盘符根 `C:/` 必须原样保留：削成 `C:` 语义完全不同（"当前盘的当前目录"），
	// 且不再匹配 `^[A-Za-z]:/`，会被形状校验当成非绝对路径而作废。
	if (!/^[A-Za-z]:\/$/.test(s)) s = s.replace(/\/+$/, "");
	return s;
}

/**
 * 归一化项目路径标签：产出**唯一形态**的绝对路径字符串，或 `""`（表示"没有项目"）。
 *
 * 步骤：去首尾空白 → 反斜杠全转正斜杠 → 去尾部多余 `/`（盘符根 `C:/` 除外）→ 去首尾成对引号
 * → 形状校验。非绝对路径一律作废（返回 `""`），**不做任何猜测式补全**。
 *
 * 参数：任意值（可能是 `undefined` / 非字符串 / 相对路径 / 带引号的脏串）。
 * 返回：`C:/dev/code/xianhua` 形态的路径，或 `""`。
 * 设计意图与边界：
 *   - **必须幂等**：`normalizeProjectTag(normalizeProjectTag(x)) === normalizeProjectTag(x)`。
 *     标签会被反复读写（回填器重跑、写侧再归一一次、召回侧比较），不幂等就会每次跑出一批新字符串，
 *     同一项目被拆成两条记录。做法是：把单趟 {@link normalizeOnce} 套用到**不动点**为止
 *     （最多 3 趟，每趟只会让字符串变短，必然收敛），这样 `""C:/a""` 这种嵌套引号也会被吃干净；
 *     绝对路径校验放在不动点**之后**，否则第一趟就会把还带引号的串误杀成空串。
 *   - **相对路径返回 `""`**：`xianhua/src`、`./A104527` 这类既不是合法 `project` 标签，
 *     又会在不同会话 cwd 下指向不同东西 —— 存进标签等于存了一颗定时炸弹，宁可不写。
 *   - 保留原始大小写（不 lower），因为标签要原样回显给用户看；大小写不敏感的比较
 *     由既有的 `projectKey` / `isUnder` 负责，不在这里做。
 */
export function normalizeProjectTag(v: unknown): string {
	if (typeof v !== "string") return "";
	let s = v.trim();
	if (!s) return "";
	// 套用到不动点 ⇒ 幂等（单趟已稳定时只跑一趟，代价可忽略）
	for (let i = 0; i < MAX_NORMALIZE_PASSES; i++) {
		const next = normalizeOnce(s);
		if (next === s) break;
		s = next;
		if (!s) return "";
	}
	// 形状校验：相对路径不是项目
	if (!/^[A-Za-z]:\//.test(s)) return "";
	return s;
}

// ══════════════════════════════════════════════════════════════
//  归属决策
// ══════════════════════════════════════════════════════════════

/**
 * 决定一条记忆最终该挂到哪个项目路径（`scope` + `project` ⇒ 单一、自洽的取值）。
 *
 * 参数：
 *   - `scope`  已归一的适用范围标签。
 *   - `project` 调用方选定的项目路径（来源可以是会话判定表 / `cwd` 最长包含 / 内容匹配 /
 *     模型裁决），可能为空或脏。
 * 返回：归一化后的项目路径，或 `""`（= 没有项目 / 判不了）。
 * 三个分支：
 *   - `self`    → 归一化后的 project（归一后为空就是空，不猜）
 *   - `global`  → `""`（**确定没有项目**；即使调用方传了路径也照样抹掉）
 *   - `unknown` → `""`（**判不了**；同样抹掉，避免下游把一个不可信的路径当过滤依据）
 *
 * 设计意图 —— 为什么把这条不变量收进一个函数，而不是让每个调用方自己判：
 * `scope` 与 `project` 两个字段必须始终自洽，否则下游必然出错。集中在这里，
 * 违规组合（`global`/`unknown` 却带着 project、`self` 却 project 为空）根本写不出来。
 * 而且这两种写反**不是小错**：召回时按 project 过滤，一写反就把一条该通用的记忆
 * 藏进某个仓库、或把一条项目专属记忆当通用件到处注入。
 */
export function projectForScope(scope: ScopeValue, project: string): string {
	return scope === "self" ? normalizeProjectTag(project) : "";
}

